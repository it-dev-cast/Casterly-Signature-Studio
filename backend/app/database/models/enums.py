import enum


class UserRole(str, enum.Enum):
    ADMIN = "ADMIN"
    EMPLOYEE = "EMPLOYEE"


class BannerStatus(str, enum.Enum):
    """Stored lifecycle states are DRAFT, PUBLISHED and ARCHIVED.

    SCHEDULED and EXPIRED are *effective* states derived from a PUBLISHED banner's
    start/end dates, so no background job is needed to flip them.
    """

    DRAFT = "DRAFT"
    SCHEDULED = "SCHEDULED"
    PUBLISHED = "PUBLISHED"
    EXPIRED = "EXPIRED"
    ARCHIVED = "ARCHIVED"


